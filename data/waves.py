def _p2(spec, end=600):
    """後編の 10 分ウェーブ表を作る。spec = [(開始秒, 敵種, 秒間出現数, 同時上限) | (秒, "boss", 敵種)]。
    通常の行は end 秒まで続く (終了秒を省略できる)"""
    out = []
    for row in spec:
        if row[1] == "boss":
            out.append(row)
        else:
            st, kind, rate, cap = row
            out.append((st, end, kind, rate, cap))
    return out


